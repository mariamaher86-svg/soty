// The Supabase dashboard editor takes one file: write paste-in-dashboard.ts = index.ts with decide.ts inlined.
//   npm run reminders
// A test checks this file is up to date, so the code she pastes is the code the tests checked.
import { readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/functions/send-reminders';
const NL = '\n';

/** Windows checkouts may give the sources CRLF line endings: the pasted file always has plain LF. */
export const unix = (s) => s.replace(/\r\n?/g, NL);

export function bundle(index, decide) {
  index = unix(index);
  decide = unix(decide);
  const lines = index
    .split(NL)
    .filter((l) => !/^import \{[^}]*\} from '\.\/decide\.ts';$/.test(l));
  const lastImport = lines.reduce((at, l, i) => (l.startsWith('import ') ? i : at), -1);
  const inlined = decide
    .split(NL)
    .filter((l) => !l.startsWith('//'))
    .join(NL)
    .replace(/^export /gm, '')
    .trim();
  lines.splice(lastImport + 1, 0, '', '// ---- decide.ts (inlined)', inlined, '// ---- end of decide.ts');
  return [
    '// GENERATED by `npm run reminders` from index.ts + decide.ts: paste this whole file into the Supabase dashboard editor.',
    "// Edit index.ts / decide.ts instead (the app's tests check decide.ts).",
    '',
    lines.join(NL),
  ].join(NL);
}

if (process.argv[1]?.endsWith('bundle-reminders.mjs')) {
  const out = bundle(readFileSync(`${dir}/index.ts`, 'utf8'), readFileSync(`${dir}/decide.ts`, 'utf8'));
  writeFileSync(`${dir}/paste-in-dashboard.ts`, out);
  console.log(`${dir}/paste-in-dashboard.ts`);
}
