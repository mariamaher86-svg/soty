// "نكلمك إزاي؟ بنت / ولد": how the app addresses the user. Feminine is the default (all source text is
// written in the feminine); in masculine mode `toMasc` turns the feminine words into masculine ones.
// Words whose meaning depends on what they describe (e.g. "جاهزة" = the person, or a song) use `g(f, m)` instead.

import { getPref, setPref } from './storage';

export type Gender = 'f' | 'm';

export function getGender(): Gender {
  return getPref('gender') === 'm' ? 'm' : 'f';
}

/** true once the user picked (until then: feminine, and the app may ask). */
export function genderChosen(): boolean {
  const v = getPref('gender');
  return v === 'm' || v === 'f';
}

export function setGender(g: Gender) {
  setPref('gender', g);
}

/** The feminine or masculine form, by the current setting. */
export function g(f: string, m: string): string {
  return getGender() === 'm' ? m : f;
}

