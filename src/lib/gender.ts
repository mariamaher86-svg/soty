/** Prefixes glued to a word in Arabic writing ("و" and, "ف" so, "ب" with, "ل" to). */
const PREFIXES = ['و', 'ف'];
const WORD = /[؀-ۿـً-ْ]+/g;

/** Feminine text → masculine (idempotent; other words untouched). */
export function toMasc(text: string): string {
  return text.replace(WORD, (w) => {
    if (MASC_WORDS[w]) return MASC_WORDS[w];
    for (const p of PREFIXES) if (w.startsWith(p) && MASC_WORDS[w.slice(1)]) return p + MASC_WORDS[w.slice(1)];
    return w;
  });
}

/** Text as shown to the current user. */
export function addr(text: string): string {
  return getGender() === 'm' ? toMasc(text) : text;
}

