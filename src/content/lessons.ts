// A lesson = sections (each a list of blocks), a summary to memorize, and a pool of quiz questions.
// Sounds are semitone offsets from the C in the user's own octave (fractions = quarter tones). Note tables for scales and
// maqamat are not typed here: they're generated from lib/theory.ts and the maqam table, so they can't contradict the app.
// In text, [[term]] or [[term|shown words]] links to the glossary below. Written in the feminine: the girl/boy system converts it.

import { MAQAMAT } from '../lib/maqam';
import type { PoolQuestion } from '../lib/lessonProgress';
import type { ScaleKind } from '../lib/theory';

export type LessonId = 'note' | 'solfege' | 'octave' | 'tone' | 'scale' | 'intervals' | 'quarter' | 'maqam' | 'maqam2' | 'chords' | 'cents' | 'tune' | 'rhythm' | 'voice';

/** Something to play: notes one after another (offsets from C, semitones), or a maqam scale. */
export interface Sound {
  notes?: number[];
  maqam?: string;
  /** seconds per note */
  dur?: number;
  /** all the notes at once (a chord) */
  together?: boolean;
  /** metronome clicks instead of notes: beat positions (in beats) at `bpm`, beat 1 of each bar accented */
  clicks?: { bpm: number; beats: number[]; perBar?: number };
}

export interface Example {
  label: string;
  sound: Sound;
}

export type Block =
  | { p: string } // a paragraph
  | { ex: string } // a worked example
  | { like: string } // an everyday comparison
  | { note: string } // something to watch out for
  | { listen: Example[] } // 🔊 buttons; the notes light up on the keyboard
  | { keys: number[]; caption?: string } // keys marked on the keyboard
  | { table: string[][] } // first row = headers
  | { scale: { kind: ScaleKind; tonic: string } } // built step by step, generated
  | { maqam: string } // a maqam's chart, generated from the table
  | { intervals: true }
  | { ajnas: true }
  | { chord: string[] } // chord symbols with their notes, generated
  | { noteValues: true }
  | { voice: { label: string; notes: number[] } } // "جربي بصوتك": the mic meter on these notes
  | { meter: number[] }
  | { links: { href: string; label: string }[] };

export interface LessonSection {
  title: string;
  blocks: Block[];
}

export interface QuizQuestion extends PoolQuestion {
  /** listening question: play this first */
  sound?: Sound;
}

export interface Lesson {
  id: LessonId;
  icon: string;
  title: string;
  sections: LessonSection[];
  /** "الخلاصة": 2–4 lines to memorize */
  summary: string[];
  /** the quiz draws from here, so a retake differs */
  pool: QuizQuestion[];
}

/** Pass mark. */
export const PASS_RATIO = 0.8;

const n = (...notes: number[]): Sound => ({ notes, dur: 0.6 });
const slow = (...notes: number[]): Sound => ({ notes, dur: 1 });
const chord = (...notes: number[]): Sound => ({ notes, dur: 1.6, together: true });
const MAJOR = [0, 2, 4, 5, 7, 9, 11, 12];
const MINOR = [0, 2, 3, 5, 7, 8, 10, 12];
const beats = (bpm: number, count: number, perBar = 100): Sound => ({ clicks: { bpm, beats: Array.from({ length: count }, (_, i) => i), perBar } });

/** A quiz question: the right answer is written first (the options are shuffled when the quiz is drawn). */
const q = (text: string, options: string[], why: string, sound?: Sound): QuizQuestion => ({ q: text, options, answer: 0, why, ...(sound ? { sound } : {}) });

