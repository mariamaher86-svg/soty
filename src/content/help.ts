/** Labels quoted «like this» in an entry. */
export function quotedLabels(e: HelpEntry): string[] {
  return [e.what, e.why, ...e.steps, ...e.numbers, ...e.tips].flatMap((t) => [...t.matchAll(/«([^»]+)»/g)].map((m) => m[1]));
}
